def compute_hash(content: str) -> str:
    """计算内容哈希值"""
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


def init_sqlite_knowledge():
    """初始化 SQLite 知识库表"""
    db = SessionLocal()
    try:
        for item in SEED_DATA:
            content_hash = compute_hash(item["content"])

            # 检查是否已存在
            existing = db.query(KnowledgeChunk).filter(
                KnowledgeChunk.title == item["title"],
                KnowledgeChunk.category == item["category"],
            ).first()

            if existing:
                print(f"  跳过（已存在）: {item['title']}")
                continue

            chunk = KnowledgeChunk(
                category=item["category"],
                title=item["title"],
                content=item["content"],
                source=item["source"],
            )
            db.add(chunk)
            print(f"  已添加: {item['title']}")

        db.commit()
        print(f"\n✓ SQLite 知识库初始化完成，共 {len(SEED_DATA)} 条记录")
    finally:
        db.close()


def init_chroma_knowledge():
    """初始化 ChromaDB 向量知识库"""
    try:
        import chromadb
        from chromadb.config import Settings as ChromaSettings
        from sentence_transformers import SentenceTransformer

        print("正在加载嵌入模型...")
        model = SentenceTransformer(settings.embedding_model)

        persist_dir = str(settings.chroma_path)
        os.makedirs(persist_dir, exist_ok=True)

        client = chromadb.PersistentClient(
            path=persist_dir,
            settings=ChromaSettings(anonymized_telemetry=False),
        )

        # 删除旧 collection 重新创建（确保数据最新）
        try:
            client.delete_collection("knowledge_vectors")
            print("  已删除旧的向量集合")
        except Exception:
            pass

        collection = client.create_collection(
            name="knowledge_vectors",
            metadata={"hnsw:space": "cosine"},
        )

        # 批量添加
        ids = []
        documents = []
        embeddings = []
        metadatas = []

        for i, item in enumerate(SEED_DATA):
            chunk_id = f"seed_{i}"
            ids.append(chunk_id)
            documents.append(item["content"])
            embeddings.append(model.encode(item["content"]).tolist())
            metadatas.append({
                "category": item["category"],
                "title": item["title"],
                "source": item["source"],
            })

        collection.add(
            ids=ids,
            documents=documents,
            embeddings=embeddings,
            metadatas=metadatas,
        )

        print(f"✓ ChromaDB 向量知识库初始化完成，共 {len(ids)} 条记录")

    except ImportError as e:
        print(f"⚠ ChromaDB 或 sentence-transformers 未安装，跳过向量化: {e}")
    except Exception as e:
        print(f"⚠ ChromaDB 初始化失败: {e}")


